"""Postprocess Austin monostatic PEC-almond RCS sweeps.

The Austin monostatic driver writes one combined CSV,

    <run-dir>/diagnostics/austin_monostatic_rcs_comparison.csv

after launching one time-domain scattering run per incident azimuth and
polarization.  This script plots the accepted RCS samples against the Austin
reference curves and reports PEC-residual gate diagnostics.  Rows whose PEC
boundary residual did not pass are not used for error statistics; they can be
shown as diagnostic markers with ``--show-failed``.
"""

