def strip_toml_comment(value: str) -> str:
    in_string = False
    escaped = False
    for index, char in enumerate(value):
        if char == "\\" and in_string:
            escaped = not escaped
            continue
        if char == '"' and not escaped:
            in_string = not in_string
        if char == "#" and not in_string:
            return value[:index].strip()
        escaped = False
    return value.strip()


def parse_toml_value(value: str):
    value = strip_toml_comment(value)
    if value.startswith('"') and value.endswith('"'):
        return value[1:-1]
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        if not inner:
            return []
        return [parse_toml_value(item.strip()) for item in inner.split(",")]
    if value.lower() == "true":
        return True
    if value.lower() == "false":
        return False
    try:
        if re.search(r"[.eE]", value):
            return float(value)
        return int(value)
    except ValueError:
        return value


def read_resolved_configuration(path: Path) -> dict[str, object]:
    if not path.is_file():
        return {}
    config: dict[str, object] = {}
    in_configuration = False
    with path.open() as stream:
        for line in stream:
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue
            if stripped.startswith("[") and stripped.endswith("]"):
                in_configuration = stripped == "[configuration]"
                continue
            if not in_configuration or "=" not in stripped:
                continue
            key, value = stripped.split("=", 1)
            config[key.strip()] = parse_toml_value(value.strip())
    return config


def read_single_csv_row(path: Path) -> dict[str, str]:
    if not path.is_file():
        raise FileNotFoundError(f"Required CSV not found: {path}")
    with path.open(newline="") as stream:
        rows = list(csv.DictReader(stream))
    if len(rows) != 1:
        raise ValueError(f"Expected one row in {path}; found {len(rows)}.")
    return rows[0]


def read_residual_summary(path: Path) -> tuple[float, float]:
    if not path.is_file():
        return math.nan, math.nan
    with path.open(newline="") as stream:
        rows = list(csv.DictReader(stream))
    if not rows:
        return math.nan, math.nan
    values = [float_or_nan(row.get("relative_rms_norm", "")) for row in rows]
    return values[-1], max_finite(values)


def interpolate_curve(curve: ReferenceCurve, phi_degrees: float) -> tuple[float, float]:
    if (
        not math.isfinite(phi_degrees)
        or phi_degrees < curve.phi_degrees[0]
        or phi_degrees > curve.phi_degrees[-1]
    ):
        return math.nan, math.nan
    dbsm = float(np.interp(phi_degrees, curve.phi_degrees, curve.rcs_dbsm))
    normalized_db = float(
        np.interp(phi_degrees, curve.phi_degrees, curve.rcs_over_lambda2_db)
    )
    return dbsm, normalized_db


def case_polarization(case_dir: Path) -> str | None:
    name = case_dir.name.upper()
    if name.endswith("_H"):
        return "H"
    if name.endswith("_V"):
        return "V"
    return None


def first_float_list_value(value: object, default: float = math.nan) -> float:
    if isinstance(value, list) and value:
        try:
            return float(value[0])
        except (TypeError, ValueError):
            return default
    try:
        return float(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return default


def recover_rows_from_cases(args: argparse.Namespace) -> list[MonostaticRow]:
    cases_dir = args.run_dir / "cases"
    if not cases_dir.is_dir():
        raise FileNotFoundError(
            f"Cannot recover rows; cases directory not found: {cases_dir}"
        )

    rows: list[MonostaticRow] = []
    for case_dir in sorted(path for path in cases_dir.iterdir() if path.is_dir()):
        pol = case_polarization(case_dir)
        if pol is None:
            continue

        config = read_resolved_configuration(
            case_dir / "config" / "resolved_config.toml"
        )
        rcs_row = read_single_csv_row(case_dir / "diagnostics" / "rcs.csv")
        final_residual, max_residual = read_residual_summary(
            case_dir / "diagnostics" / "pec_boundary_residual.csv"
        )
        residual_pass = (
            final_residual <= args.max_final_relative_rms
            and max_residual <= args.max_sampled_relative_rms
        )

        component = "phi" if pol == "H" else "theta"
        component_key = "abs_Ephi" if pol == "H" else "abs_Etheta"
        amplitude = abs(float(config.get("amplitude", 1.0)))
        wavelength = float(config.get("wavelength", math.nan))
        far_field_component = float_or_nan(rcs_row.get(component_key, ""))
        sigma = (
            4.0
            * math.pi
            * far_field_component
            * far_field_component
            / max(amplitude * amplitude, EPS)
        )
        sigma_dbsm = 10.0 * math.log10(sigma) if sigma > 0.0 else math.nan
        sigma_over_lambda2 = sigma / max(wavelength * wavelength, EPS)
        sigma_over_lambda2_db = (
            10.0 * math.log10(sigma_over_lambda2)
            if sigma_over_lambda2 > 0.0
            else math.nan
        )

        phi_degrees = first_float_list_value(
            config.get("rcs_phi_degrees"),
            float_or_nan(rcs_row.get("phi_degrees", "")),
        )
        incident_direction = config.get("incident_propagation_direction", [])
        incident_polarization = config.get("incident_polarization", [])
        incident_dir = [
            first_float_list_value(incident_direction[index : index + 1])
            if isinstance(incident_direction, list) and len(incident_direction) > index
            else math.nan
            for index in range(3)
        ]
        incident_pol = [
            first_float_list_value(incident_polarization[index : index + 1])
            if isinstance(incident_polarization, list)
            and len(incident_polarization) > index
            else math.nan
            for index in range(3)
        ]
        reference_path = reference_file(
            args.reference_dir,
            args.reference_kind,
            args.frequency_key,
            pol,
        )
        curve = read_reference_curve(reference_path, pol, args.frequency_key)
        reference_dbsm, reference_norm_db = interpolate_curve(curve, phi_degrees)
        error_db = sigma_over_lambda2_db - reference_norm_db
        status = "PASS"
        message = "PEC residual gate passed"
        if not residual_pass:
            status = "RESIDUAL_FAIL"
            message = (
                "PEC residual gate failed; benchmark error is diagnostic only"
            )

        rows.append(
            MonostaticRow(
                status=status,
                message=message,
                polarization=pol,
                component=component,
                frequency_key=args.frequency_key,
                reference_kind=args.reference_kind,
                incident_theta_degrees=90.0,
                incident_phi_degrees=phi_degrees,
                observation_theta_degrees=float_or_nan(
                    rcs_row.get("theta_degrees", "")
                ),
                observation_phi_degrees=float_or_nan(rcs_row.get("phi_degrees", "")),
                incident_dir_x=incident_dir[0],
                incident_dir_y=incident_dir[1],
                incident_dir_z=incident_dir[2],
                incident_pol_x=incident_pol[0],
                incident_pol_y=incident_pol[1],
                incident_pol_z=incident_pol[2],
                rcs_component=sigma,
                rcs_component_dbsm=sigma_dbsm,
                rcs_component_over_lambda2=sigma_over_lambda2,
                rcs_component_over_lambda2_db=sigma_over_lambda2_db,
                reference_rcs_dbsm=reference_dbsm,
                reference_rcs_over_lambda2_db=reference_norm_db,
                error_db=error_db,
                samples=int_or_zero(rcs_row.get("samples", "")),
                window_sum=float_or_nan(rcs_row.get("window_sum", "")),
                final_pec_relative_rms=final_residual,
                max_sampled_pec_relative_rms=max_residual,
                final_time=float(config.get("final_time", math.nan)),
                steps=int(config.get("steps", 0)),
                dt=float(config.get("dt", math.nan)),
                case_output_dir=str(case_dir),
                reference_file=reference_path,
            )
        )

    if not rows:
        raise ValueError(
            f"Cannot recover rows; no monostatic case outputs found in {cases_dir}"
        )
    return sorted(rows, key=lambda item: (item.polarization, item.incident_phi_degrees))


def read_reference_curve(path: Path, polarization: str, frequency_key: str) -> ReferenceCurve:
    if not path.is_file():
        raise FileNotFoundError(f"Austin reference file not found: {path}")
    phi: list[float] = []
    dbsm: list[float] = []
    frequencies: list[float] = []
    with path.open() as stream:
        for line_number, line in enumerate(stream, start=1):
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue
            fields = stripped.split()
            if len(fields) < 4:
                raise ValueError(f"Malformed reference row {line_number} in {path}")
            frequencies.append(float(fields[0]))
            phi.append(float(fields[2]))
            dbsm.append(float(fields[3]))
    if not phi:
        raise ValueError(f"Austin reference file contains no data rows: {path}")
    frequency_hz = float(np.mean(frequencies))
    wavelength = 299_792_458.0 / frequency_hz
    phi_array = np.asarray(phi, dtype=float)
    dbsm_array = np.asarray(dbsm, dtype=float)
    order = np.argsort(phi_array)
    phi_array = phi_array[order]
    dbsm_array = dbsm_array[order]
    normalized_db = dbsm_array - 20.0 * np.log10(wavelength)
    return ReferenceCurve(
        polarization=polarization,
        frequency_key=frequency_key,
        reference_file=path,
        phi_degrees=phi_array,
        rcs_dbsm=dbsm_array,
        rcs_over_lambda2_db=normalized_db,
        rcs_over_lambda2=np.power(10.0, normalized_db / 10.0),
    )


def reference_curves(rows: list[MonostaticRow]) -> dict[str, ReferenceCurve]:
    curves: dict[str, ReferenceCurve] = {}
    for row in rows:
        if row.polarization in curves:
            continue
        if str(row.reference_file) in {"", "NaN"}:
            continue
        curves[row.polarization] = read_reference_curve(
            row.reference_file,
            row.polarization,
            row.frequency_key,
        )
    return curves


def finite(values: Iterable[float]) -> list[float]:
    return [value for value in values if math.isfinite(value)]


def rms(values: Iterable[float]) -> float:
    values = finite(values)
    if not values:
        return math.nan
    return math.sqrt(sum(value * value for value in values) / len(values))


def max_abs(values: Iterable[float]) -> float:
    values = finite(values)
    if not values:
        return math.nan
    return max(abs(value) for value in values)


def max_finite(values: Iterable[float]) -> float:
    values = finite(values)
    if not values:
        return math.nan
    return max(values)


def db_to_linear(value: float) -> float:
    if not math.isfinite(value):
        return math.nan
    return 10.0 ** (value / 10.0)


def configure_matplotlib() -> None:
    plt.rcParams.update(
        {
            "font.size": 11,
            "axes.labelsize": 12,
            "axes.titlesize": 13,
            "legend.fontsize": 9,
            "xtick.labelsize": 10,
            "ytick.labelsize": 10,
            "axes.linewidth": 0.9,
            "lines.linewidth": 2.0,
            "savefig.bbox": "tight",
        }
    )


def color_for_pol(polarization: str) -> str:
    return "#3f2e7e" if polarization == "H" else "#d95f02"


def marker_for_pol(polarization: str) -> str:
    return "o" if polarization == "H" else "s"


def title_text(prefix: str | None, suffix: str) -> str:
    if prefix:
        return f"{prefix}: {suffix}"
    return suffix


def save_figure(fig: plt.Figure, path: Path, write_png: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path)
    if write_png:
        fig.savefig(path.with_suffix(".png"), dpi=300)
    plt.close(fig)


def rows_for_plot(
    rows: list[MonostaticRow],
    polarization: str,
    include_failed: bool,
) -> tuple[list[MonostaticRow], list[MonostaticRow]]:
    selected = [row for row in rows if row.polarization == polarization]
    passed = [row for row in selected if row.passed]
    failed = [row for row in selected if not row.passed] if include_failed else []
    return passed, failed


def annotate_no_pass(ax: plt.Axes) -> None:
    ax.text(
        0.5,
        0.5,
        "No selected rows passed the PEC residual gate",
        transform=ax.transAxes,
        ha="center",
        va="center",
        bbox={"boxstyle": "round", "facecolor": "white", "alpha": 0.85},
    )


def plot_comparison(
    path: Path,
    rows: list[MonostaticRow],
    curves: dict[str, ReferenceCurve],
    polarizations: list[str],
    title: str | None,
    write_png: bool,
    show_failed: bool,
    linear: bool,
) -> None:
    configure_matplotlib()
    fig, ax = plt.subplots(figsize=(7.4, 4.6))
    plotted_pass = False
    plotted_failed = False

    for pol in polarizations:
        color = color_for_pol(pol)
        curve = curves.get(pol)
        if curve is not None:
            reference_values = (
                curve.rcs_over_lambda2 if linear else curve.rcs_over_lambda2_db
            )
            ax.plot(
                curve.phi_degrees,
                reference_values,
                color=color,
                linestyle="-",
                label=f"Austin {pol} ({curve.frequency_key})",
            )

        passed, failed = rows_for_plot(rows, pol, show_failed)
        if passed:
            x = np.array([row.incident_phi_degrees for row in passed], dtype=float)
            y = np.array(
                [
                    row.rcs_component_over_lambda2
                    if linear
                    else row.rcs_component_over_lambda2_db
                    for row in passed
                ],
                dtype=float,
            )
            ax.plot(
                x,
                y,
                color=color,
                linestyle="none",
                marker=marker_for_pol(pol),
                markerfacecolor="white",
                markeredgewidth=1.6,
                markersize=5.0,
                label=f"DiscoGMPI {pol} ({passed[0].component})",
            )
            plotted_pass = True
        if failed:
            x = np.array([row.incident_phi_degrees for row in failed], dtype=float)
            y = np.array(
                [
                    row.rcs_component_over_lambda2
                    if linear
                    else row.rcs_component_over_lambda2_db
                    for row in failed
                ],
                dtype=float,
            )
            ax.plot(
                x,
                y,
                color=color,
                linestyle="none",
                marker="x",
                alpha=0.45,
                markersize=5.0,
                label=f"DiscoGMPI {pol} residual fail",
            )
            plotted_failed = True

    if not plotted_pass and not plotted_failed:
        annotate_no_pass(ax)
    ax.set_xlabel(r"Incident/observation azimuth $\phi_i$ [deg]")
    if linear:
        ax.set_ylabel(r"$\sigma/\lambda^2$")
        ax.set_yscale("log")
        ax.set_title(title_text(title, "normalized RCS, linear scale"))
    else:
        ax.set_ylabel(r"$10\log_{10}(\sigma/\lambda^2)$ [dB]")
        ax.set_title(title_text(title, "normalized RCS"))
    ax.grid(True, which="major", color="0.86", linewidth=0.9)
    ax.grid(True, which="minor", color="0.93", linewidth=0.5)
    ax.minorticks_on()
    if plotted_pass or plotted_failed:
        ax.legend(frameon=True, framealpha=0.95)
    save_figure(fig, path, write_png)


def plot_error(
    path: Path,
    rows: list[MonostaticRow],
    polarizations: list[str],
    title: str | None,
    write_png: bool,
) -> None:
    configure_matplotlib()
    fig, ax = plt.subplots(figsize=(7.4, 4.2))
    plotted = False
    for pol in polarizations:
        passed = [
            row
            for row in rows
            if row.polarization == pol and row.passed and math.isfinite(row.error_db)
        ]
        if not passed:
            continue
        ax.plot(
            [row.incident_phi_degrees for row in passed],
            [row.error_db for row in passed],
            color=color_for_pol(pol),
            linestyle="-",
            marker=marker_for_pol(pol),
            markerfacecolor="white",
            markeredgewidth=1.4,
            markersize=4.5,
            label=f"{pol}: DiscoGMPI - Austin",
        )
        plotted = True
    if not plotted:
        annotate_no_pass(ax)
    ax.axhline(0.0, color="0.25", linestyle="--", linewidth=1.0)
    ax.set_xlabel(r"Incident/observation azimuth $\phi_i$ [deg]")
    ax.set_ylabel(r"$\Delta$ RCS [dB]")
    ax.set_title(title_text(title, "normalized RCS error"))
    ax.grid(True, which="major", color="0.86", linewidth=0.9)
    ax.grid(True, which="minor", color="0.93", linewidth=0.5)
    ax.minorticks_on()
    if plotted:
        ax.legend(frameon=True, framealpha=0.95)
    save_figure(fig, path, write_png)


def plot_residuals(
    path: Path,
    rows: list[MonostaticRow],
    polarizations: list[str],
    args: argparse.Namespace,
    title: str | None,
    write_png: bool,
) -> None:
    configure_matplotlib()
    fig, ax = plt.subplots(figsize=(7.4, 4.2))
    plotted = False
    for pol in polarizations:
        selected = [row for row in rows if row.polarization == pol]
        if not selected:
            continue
        color = color_for_pol(pol)
        x = [row.incident_phi_degrees for row in selected]
        ax.plot(
            x,
            [max(row.final_pec_relative_rms, EPS) for row in selected],
            color=color,
            linestyle="-",
            marker=marker_for_pol(pol),
            markerfacecolor="white",
            markeredgewidth=1.4,
            markersize=4.5,
            label=f"{pol} final RMS",
        )
        ax.plot(
            x,
            [max(row.max_sampled_pec_relative_rms, EPS) for row in selected],
            color=color,
            linestyle="--",
            marker=marker_for_pol(pol),
            markerfacecolor=color,
            markeredgewidth=1.0,
            markersize=3.8,
            label=f"{pol} max sampled RMS",
        )
        plotted = True
    if not plotted:
        annotate_no_pass(ax)
    ax.axhline(
        args.max_final_relative_rms,
        color="0.25",
        linestyle="-.",
        linewidth=1.0,
        label="final gate",
    )
    ax.axhline(
        args.max_sampled_relative_rms,
        color="0.45",
        linestyle=":",
        linewidth=1.2,
        label="sampled gate",
    )
    ax.set_yscale("log")
    ax.set_xlabel(r"Incident/observation azimuth $\phi_i$ [deg]")
    ax.set_ylabel(r"PEC residual relative RMS")
    ax.set_title(title_text(title, "PEC boundary residual gate"))
    ax.grid(True, which="major", color="0.86", linewidth=0.9)
    ax.grid(True, which="minor", color="0.93", linewidth=0.5)
    ax.minorticks_on()
    if plotted:
        ax.legend(frameon=True, framealpha=0.95, ncol=2)
    save_figure(fig, path, write_png)


