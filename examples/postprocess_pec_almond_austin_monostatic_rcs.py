def parse_polarizations(value: str) -> list[str]:
    stripped = value.strip()
    if stripped.lower() == "both":
        return ["H", "V"]
    polarizations: list[str] = []
    for entry in stripped.split(","):
        pol = entry.strip().upper()
        if pol not in {"H", "V"}:
            raise ValueError("--polarization entries must be H, V, or both.")
        if pol not in polarizations:
            polarizations.append(pol)
    if not polarizations:
        raise ValueError("--polarization requires H, V, or both.")
    return polarizations


def float_or_nan(value: str) -> float:
    stripped = value.strip()
    if not stripped:
        return math.nan
    try:
        return float(stripped)
    except ValueError:
        return math.nan


def int_or_zero(value: str) -> int:
    try:
        return int(value)
    except ValueError:
        return 0


