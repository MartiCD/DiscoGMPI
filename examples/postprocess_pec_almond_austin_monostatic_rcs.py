@dataclass(frozen=True)
class MonostaticRow:
    status: str
    message: str
    polarization: str
    component: str
    frequency_key: str
    reference_kind: str
    incident_theta_degrees: float
    incident_phi_degrees: float
    observation_theta_degrees: float
    observation_phi_degrees: float
    incident_dir_x: float
    incident_dir_y: float
    incident_dir_z: float
    incident_pol_x: float
    incident_pol_y: float
    incident_pol_z: float
    rcs_component: float
    rcs_component_dbsm: float
    rcs_component_over_lambda2: float
    rcs_component_over_lambda2_db: float
    reference_rcs_dbsm: float
    reference_rcs_over_lambda2_db: float
    error_db: float
    samples: int
    window_sum: float
    final_pec_relative_rms: float
    max_sampled_pec_relative_rms: float
    final_time: float
    steps: int
    dt: float
    case_output_dir: str
    reference_file: Path

    @property
    def passed(self) -> bool:
        return self.status.upper() == "PASS"


@dataclass(frozen=True)
class ReferenceCurve:
    polarization: str
    frequency_key: str
    reference_file: Path
    phi_degrees: np.ndarray
    rcs_dbsm: np.ndarray
    rcs_over_lambda2_db: np.ndarray
    rcs_over_lambda2: np.ndarray


