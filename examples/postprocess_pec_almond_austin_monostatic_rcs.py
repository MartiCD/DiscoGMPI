def latex_value(value: float, digits: int = 3) -> str:
    if not math.isfinite(value):
        return r"\mathrm{n/a}"
    return f"{value:.{digits}g}"


def write_latex_summary(
    path: Path,
    rows: list[MonostaticRow],
    polarizations: list[str],
) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as stream:
        stream.write(
            "% Generated by examples/postprocess_pec_almond_austin_monostatic_rcs.py\n"
        )
        stream.write("\\begin{tabular}{lrrrrrr}\n")
        stream.write("\\hline\n")
        stream.write(
            "Pol. & Rows & Pass & Fail & "
            "$\\max |\\Delta|$ [dB] & RMS $\\Delta$ [dB] & "
            "$\\max r_{\\mathrm{PEC}}$ \\\\\n"
        )
        stream.write("\\hline\n")
        for pol in polarizations:
            selected = [row for row in rows if row.polarization == pol]
            passed = [row for row in selected if row.passed]
            failed = [row for row in selected if not row.passed]
            errors = [row.error_db for row in passed]
            residuals = [
                max(row.final_pec_relative_rms, row.max_sampled_pec_relative_rms)
                for row in selected
            ]
            stream.write(
                f"{pol} & {len(selected)} & {len(passed)} & {len(failed)} & "
                f"{latex_value(max_abs(errors))} & {latex_value(rms(errors))} & "
                f"{latex_value(max_finite(residuals))} \\\\\n"
            )
        stream.write("\\hline\n")
        stream.write("\\end{tabular}\n")
    return path


def selected_rows(rows: list[MonostaticRow], polarizations: list[str]) -> list[MonostaticRow]:
    return [row for row in rows if row.polarization in polarizations]


def print_summary(rows: list[MonostaticRow], polarizations: list[str]) -> None:
    print("Austin monostatic PEC almond postprocessing")
    print("-------------------------------------------")
    for pol in polarizations:
        selected = [row for row in rows if row.polarization == pol]
        passed = [row for row in selected if row.passed]
        failed = [row for row in selected if not row.passed]
        errors = [row.error_db for row in passed]
        print(
            f"{pol}: rows={len(selected)}, pass={len(passed)}, "
            f"fail={len(failed)}, max|error|={latex_value(max_abs(errors))} dB, "
            f"rms error={latex_value(rms(errors))} dB"
        )


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    polarizations = parse_polarizations(args.polarization)
    recovered_from_cases = False
    try:
        all_rows = read_monostatic_rows(input_csv_path(args))
    except (FileNotFoundError, ValueError) as error:
        if not args.recover_from_cases:
            raise
        print(
            "Combined monostatic CSV could not be used "
            f"({error}); recovering rows from case outputs.",
            file=sys.stderr,
        )
        all_rows = recover_rows_from_cases(args)
        recovered_from_cases = True

    rows = selected_rows(all_rows, polarizations)
    if not rows:
        raise ValueError("No rows match the requested polarization selection.")
    curves = reference_curves(rows)
    (
        postprocessed_csv,
        latex_output,
        db_plot,
        linear_plot,
        error_plot,
        residual_plot,
    ) = default_outputs(args)

    if recovered_from_cases:
        try:
            repaired_path = write_combined_comparison_csv(input_csv_path(args), all_rows)
            print(f"Repaired combined comparison CSV: {repaired_path}")
        except OSError as error:
            print(
                "Could not repair combined comparison CSV "
                f"{input_csv_path(args)} ({error}); continuing with plots.",
                file=sys.stderr,
            )

    write_postprocessed_csv(postprocessed_csv, rows)
    write_latex_summary(latex_output, rows, polarizations)
    plot_comparison(
        db_plot,
        rows,
        curves,
        polarizations,
        args.title,
        args.write_png,
        args.show_failed,
        linear=False,
    )
    plot_comparison(
        linear_plot,
        rows,
        curves,
        polarizations,
        args.title,
        args.write_png,
        args.show_failed,
        linear=True,
    )
    plot_error(error_plot, rows, polarizations, args.title, args.write_png)
    plot_residuals(residual_plot, rows, polarizations, args, args.title, args.write_png)

    print_summary(rows, polarizations)
    print(f"Postprocessed CSV: {postprocessed_csv}")
    print(f"LaTeX summary:     {latex_output}")
    print(f"dB plot:           {db_plot}")
    print(f"linear plot:       {linear_plot}")
    print(f"error plot:        {error_plot}")
    print(f"residual plot:     {residual_plot}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
