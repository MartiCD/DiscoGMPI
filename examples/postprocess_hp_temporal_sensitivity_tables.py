#!/usr/bin/env python3
"""Create fixed-mesh dt, dt/2, dt/4 LaTeX tables for the hp campaign."""

import argparse
import csv
import math
from pathlib import Path
from postprocess_convergence_csv_tables import is_mixed_csv


ERROR_COLUMNS = {
    "final": ("final_l2_space_electric_error", "final_l2_space_magnetic_error"),
    "max-time": ("linf_time_l2_space_electric_error",
                 "linf_time_l2_space_magnetic_error"),
}


def scientific(value):
    mantissa, exponent = f"{float(value):.2e}".split("e")
    return rf"${mantissa}\times 10^{{{int(exponent)}}}$"


def read_rows(path, case, flux, nodal_set, mesh_family, level):
    selected = {}
    with path.open(newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            mode = row.get("campaign_mode", "") or row.get("case", "")
            mode = {"periodic": "plane_wave", "cavity": "pec_cavity"}.get(mode, mode)
            family = row.get("campaign_mesh_family", "") or row.get("mesh_family", "")
            if (mode != case or row["flux"] != flux or family != mesh_family or
                    row["nodal_set"].replace("_", "-") != nodal_set.replace("_", "-") or
                    int(row.get("campaign_level", "") or (int(row["mesh_level"]) + 1)) != level):
                continue
            key = (int(row["order"]), int(row.get("time_factor", "1") or "1"))
            if key in selected:
                raise ValueError(f"Duplicate p={key[0]}, time factor={key[1]}")
            selected[key] = row
    return selected


def render(case, flux, mode, family, nodal, level, rows, source, mixed=False):
    ekey, hkey = ERROR_COLUMNS[mode]
    factors = (1, 2, 4)
    complete_orders = [p for p in sorted({key[0] for key in rows})
                       if all((p, factor) in rows for factor in factors)]
    if not complete_orders:
        raise ValueError(f"No complete dt, dt/2, dt/4 set for {case}/{flux}/{family}/M{level}")
    lines = [
        "% Generated by examples/postprocess_hp_temporal_sensitivity_tables.py.",
        f"% Source: {source}",
        r"\begin{table}[p]", r"  \centering",
        (r"  \caption{Fixed-mesh temporal sensitivity for the " +
         case.replace("_", r"\_") + f", {flux} flux, {family} meshes, " +
         f"{nodal} nodes, level M{level}, using {mode} spatial $L^2$ errors." +
         (r" Mixed spaces use $p_E=p$, $p_H=p+1$ and ESPRK order $p+2$." if mixed else "") + "}"),
        r"  \setlength{\tabcolsep}{5pt}",
        r"  \begin{tabular}{@{}rrccc@{}}", r"    \toprule",
        r"    $p$ & $\Delta t/\Delta t_0$ & $\Delta t$ & $\lVert e_E\rVert_2$ & $\lVert e_H\rVert_2$ \\",
        r"    \midrule",
    ]
    for p in complete_orders:
        for index, factor in enumerate(factors):
            row = rows[p, factor]
            lines.append(
                f"    {p if index == 1 else ''} & $1/{factor}$ & "
                f"{scientific(row['dt'])} & {scientific(row[ekey])} & "
                f"{scientific(row[hkey])} \\\\")
        if p != complete_orders[-1]:
            lines.extend((r"    \midrule", r"    \addlinespace[2pt]"))
    lines.extend((r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""))
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path,
                        default=Path("output/hp_isoresolution/convergence.csv"))
    parser.add_argument("--output-dir", type=Path,
                        default=Path("output/hp_isoresolution/latex_tables/temporal"))
    parser.add_argument("--cases", nargs="+", choices=("plane_wave", "pec_cavity"),
                        default=("plane_wave", "pec_cavity"))
    parser.add_argument("--fluxes", nargs="+", choices=("centered", "alternating"),
                        default=("centered", "alternating"))
    parser.add_argument("--error-modes", nargs="+", choices=tuple(ERROR_COLUMNS),
                        default=("final", "max-time"))
    parser.add_argument("--mesh-family", choices=("unstructured", "structured"),
                        default="unstructured")
    parser.add_argument("--nodal-set", default="equispaced")
    parser.add_argument("--level", type=int, default=4)
    args = parser.parse_args()
    if not args.input.is_file():
        raise FileNotFoundError(args.input)
    mixed = is_mixed_csv(args.input)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    outputs = []
    for case in args.cases:
        for flux in args.fluxes:
            rows = read_rows(args.input, case, flux, args.nodal_set,
                             args.mesh_family, args.level)
            for mode in args.error_modes:
                output = args.output_dir / f"{case}_{flux}_{mode}_M{args.level}.tex"
                output.write_text(render(case, flux, mode, args.mesh_family,
                                         args.nodal_set, args.level, rows,
                                         args.input, mixed), encoding="utf-8")
                outputs.append(output)
    print(f"Wrote {len(outputs)} temporal-sensitivity tables to {args.output_dir}")


if __name__ == "__main__":
    main()
